#!/usr/bin/env bash
# install-hooks.sh — instaluje hooki git (pre-commit, pre-push).
#
# Zasady:
#   * nie nadpisujemy cudzych hooków bez backupu
#   * bramki opcjonalne (preflight, epistemic) odpalają się TYLKO gdy katalog istnieje
#     -> brak tarcia przy adopcji, brak cichego "pominięto"
#   * każda bramka jest fail-closed i ma własny kod wyjścia
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

if [[ ! -d .git ]]; then
  echo "⚠️  Brak katalogu .git — nie ma gdzie zainstalować hooków."
  exit 1
fi

mkdir -p .git/hooks
STAMP="$(date +%Y%m%d-%H%M%S)"

backup_if_foreign() {
  local hook="$1"
  if [[ -f ".git/hooks/$hook" ]] && ! grep -q "HHH-HARNESS" ".git/hooks/$hook" 2>/dev/null; then
    cp ".git/hooks/$hook" ".git/hooks/$hook.bak-$STAMP"
    echo "   ↳ istniejący $hook zachowany jako $hook.bak-$STAMP"
  fi
}

cat > .git/hooks/pre-commit <<'HOOK'
#!/usr/bin/env bash
# HHH-HARNESS pre-commit (generated by scripts/install-hooks.sh)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
PROFILE="$(grep -E '^profile=' hhh.profile 2>/dev/null | cut -d= -f2 || echo hilux)"
[[ "$PROFILE" == "full" ]] || PROFILE="hilux"

echo "🐎 [HHH] 1/4 integralność bramek (hash-pin)"
bash scripts/gate-lock.sh --check

echo "🐎 [HHH] 2/4 Inception Gate (wywiad przed IN_PROGRESS) [profil: $PROFILE]"
if [[ "$PROFILE" != "full" ]]; then
  echo "   (hilux: Inception Gate odpala się w CI; lokalnie go pomijam dla szybkości)"
elif [[ -f docs/tasks/ACTIVE.md ]]; then
  python3 scripts/docs-provenance.py --check
else
  echo "   (brak docs/tasks/ACTIVE.md — pomijam; to nie jest bramka, bo nie ma rejestru zadań)"
fi

echo "🐎 [HHH] 3/4 Preflight (myśl i posprzątaj przed kodem)"
if [[ -d docs/preflight ]]; then
  # tylko zmiany TREŚCI (tryb pliku, np. chmod +x, nie jest "kodem do preflight")
  staged_code="$(git diff --cached --numstat | awk '$1 != "0" || $2 != "0" {print $3}' \
    | grep -E '\.(ts|tsx|js|jsx|py|go|rs|vue|svelte)$' || true)"
  if [[ -n "$staged_code" ]]; then
    ticket="$(grep -B0 -A0 -oE 'CP-[0-9]+[^|]*\|[^|]*IN_PROGRESS' docs/tasks/ACTIVE.md 2>/dev/null | grep -oE 'CP-[0-9]+' | head -1 || true)"
    [[ -z "$ticket" ]] && ticket="$(grep -oE 'CP-[0-9]+' docs/tasks/ACTIVE.md 2>/dev/null | head -1 || true)"
    staged_pf="$(git diff --cached --name-only -- 'docs/preflight/*.json' | grep -v '\.gaming\.json$' | head -1 || true)"
    if [[ -n "$ticket" && -f "docs/preflight/$ticket.json" ]]; then
      python3 scripts/preflight-gate.py --file "docs/preflight/$ticket.json"
    elif [[ -n "$staged_pf" ]]; then
      echo "   (brak biletu w ACTIVE.md — waliduję artefakt z indeksu: $staged_pf)"
      python3 scripts/preflight-gate.py --file "$staged_pf"
    else
      echo "🚩 Kod w indeksie bez artefaktu preflight (docs/preflight/${ticket:-CP-XXX}.json)."
      echo "   Najpierw: zanurkuj w pliki, wpisz cytaty, zaplanuj subtract. Reguła 7.19."
      exit 1
    fi
  else
    echo "   (brak plików kodu w indeksie — nie ma czego preflightować)"
  fi
else
  echo "   (katalog docs/preflight nie istnieje — pomijam; utwórz go, aby włączyć Regułę 7.19)"
fi

echo "🐎 [HHH] 4/4 Epistemic Gate (dowody wykonywalne) [profil: $PROFILE]"
if [[ "$PROFILE" != "full" ]]; then
  echo "   (hilux: dowody weryfikuje pre-push/CI, nie każdy commit — oszczędza czas)"
elif [[ -d docs/epistemic ]]; then
  ticket="$(grep -oE 'CP-[0-9]+' docs/tasks/ACTIVE.md 2>/dev/null | head -1 || true)"
  if [[ -n "$ticket" && -f "docs/epistemic/$ticket.json" ]]; then
    python3 scripts/epistemic-gate.py --file "docs/epistemic/$ticket.json"
  else
    echo "   (brak docs/epistemic/${ticket:-CP-XXX}.json — sprawdzenie dowodów nastąpi przed REVIEW)"
  fi
else
  echo "   (katalog docs/epistemic nie istnieje — pomijam; utwórz go, aby wymagać dowodów)"
fi

echo "✅ [HHH] pre-commit OK"
HOOK

cat > .git/hooks/pre-push <<'HOOK'
#!/usr/bin/env bash
# HHH-HARNESS pre-push (generated by scripts/install-hooks.sh)
set -uo pipefail
cd "$(git rev-parse --show-toplevel)"

echo "🐎 [HHH] Adversarial Review (linie dodawane, prawdziwe lokalizacje)"
bash scripts/adversarial-review.sh origin/main

if [[ -d docs/decisions ]]; then
  echo "🐎 [HHH] Decision Gate: każda decyzja w repo musi być podpisana"
  shopt -s nullglob
  for d in docs/decisions/*/; do
    ticket="$(basename "$d")"
    case "$ticket" in *.gaming) continue ;; esac
    for f in "$d"*.json; do
      step="$(basename "$f" .json)"
      python3 scripts/decision-gate.py --verify --ticket "$ticket" --step "$step" || exit 1
    done
  done
  shopt -u nullglob
fi

PROFILE="$(grep -E '^profile=' hhh.profile 2>/dev/null | cut -d= -f2 || echo hilux)"
if [[ -d docs/epistemic && "$PROFILE" == "full" ]]; then
  shopt -s nullglob
  files=(docs/epistemic/*.json)
  shopt -u nullglob
  for f in "${files[@]}"; do
    echo "🐎 [HHH] Epistemic Gate --execute: $f"
    python3 scripts/epistemic-gate.py --file "$f" --execute
  done
fi

if [[ -f hidden/manifest.json ]]; then
  echo "🐎 [HHH] Acceptance Gate: testy, których agent nie widzi"
  python3 scripts/acceptance-gate.py --run || exit $?
fi

echo "✅ [HHH] pre-push OK"
HOOK

backup_if_foreign pre-commit
backup_if_foreign pre-push
chmod +x .git/hooks/pre-commit .git/hooks/pre-push

echo "✅ Hooki zainstalowane: .git/hooks/pre-commit, .git/hooks/pre-push"
echo "   Aby wyłączyć bramkę: usuń katalog (docs/preflight lub docs/epistemic) — świadoma decyzja, widoczna w PR."
